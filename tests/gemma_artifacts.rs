use std::path::{Path, PathBuf};

use burn::{
    backend::Flex,
    tensor::{Int, Tensor, TensorData, backend::Backend},
};
use serde_json::Value;
use sha2::{Digest, Sha256};
use transformers::{
    AutoCausalLm, AutoLoadOptions, CausalLmInput, DecodeInput, ForwardOptions, LogitsSelection,
    TokenMask,
    attention::AttentionConnectivity,
    cache::CacheConfig,
    checkpoint::{DTypePolicy, LoadOptions, TensorDType},
    models::AutoCausalDecodeState,
};

/// Default absolute logit tolerance; see the module documentation.
const DEFAULT_TOLERANCE: f32 = 1e-3;

/// Default absolute logit tolerance of the long-context bundle; see the module documentation.
const DEFAULT_LONG_TOLERANCE: f32 = 5e-3;

/// Default minimum number of decisive greedy tokens that must be compared.
const DEFAULT_MIN_GREEDY: usize = 2;

/// One prompt of the reference bundle.
struct Prompt {
    /// Token IDs of the unpadded prompt.
    tokens: Vec<i64>,
    /// Row-major `[tokens, vocabulary]` logits.
    logits: Vec<f32>,
}

/// A parsed reference bundle.
struct Reference {
    /// Vocabulary size `V`.
    vocabulary: usize,
    /// Prompts in bundle order.
    prompts: Vec<Prompt>,
    /// Greedy continuation of prompt 0 as `(token, margin)`.
    greedy: Vec<(i64, f32)>,
    /// SHA-256 of the configuration the bundle was generated from.
    config_sha256: String,
}

impl Reference {
    /// Reads and checks a bundle directory.
    fn read(root: &Path) -> Self {
        let manifest: Value =
            serde_json::from_str(&std::fs::read_to_string(root.join("reference.json")).unwrap())
                .unwrap();
        let vocabulary = manifest["vocabulary_size"].as_u64().unwrap() as usize;
        let prompts = manifest["prompts"]
            .as_array()
            .unwrap()
            .iter()
            .map(|prompt| {
                let tokens: Vec<i64> = serde_json::from_value(prompt["token_ids"].clone()).unwrap();
                let file = root.join(prompt["logits_file"].as_str().unwrap());
                let bytes = std::fs::read(&file).unwrap();
                assert_eq!(
                    hex(&Sha256::digest(&bytes)),
                    prompt["logits_sha256"].as_str().unwrap(),
                    "{} is corrupted",
                    file.display()
                );
                let logits: Vec<f32> = bytes
                    .as_chunks::<4>()
                    .0
                    .iter()
                    .map(|chunk| f32::from_le_bytes(*chunk))
                    .collect();
                assert_eq!(logits.len(), tokens.len() * vocabulary);
                Prompt { tokens, logits }
            })
            .collect();
        let greedy = manifest["greedy"]["steps"]
            .as_array()
            .unwrap()
            .iter()
            .map(|step| {
                (
                    step["token"].as_i64().unwrap(),
                    step["margin"].as_f64().unwrap() as f32,
                )
            })
            .collect();
        Self {
            vocabulary,
            prompts,
            greedy,
            config_sha256: manifest["provenance"]["config_sha256"]
                .as_str()
                .unwrap()
                .into(),
        }
    }
}

/// Lower-case hexadecimal digest.
fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

/// Returns the directory named by the environment variable `name`.
fn directory(name: &str) -> PathBuf {
    std::env::var_os(name)
        .map(PathBuf::from)
        .unwrap_or_else(|| panic!("set {name}; see the module documentation"))
}

/// Returns the absolute logit tolerance: `TRANSFORMERS_GEMMA_TOLERANCE` or [`DEFAULT_TOLERANCE`].
fn tolerance() -> f32 {
    float_variable("TRANSFORMERS_GEMMA_TOLERANCE", DEFAULT_TOLERANCE)
}

/// Returns the long-context tolerance: `TRANSFORMERS_GEMMA_LONG_TOLERANCE` or [`DEFAULT_LONG_TOLERANCE`].
fn long_tolerance() -> f32 {
    float_variable("TRANSFORMERS_GEMMA_LONG_TOLERANCE", DEFAULT_LONG_TOLERANCE)
}

/// Parses the float environment variable `name`, or returns `default`.
fn float_variable(name: &str, default: f32) -> f32 {
    std::env::var(name)
        .map(|value| value.parse().expect("tolerance must be a float"))
        .unwrap_or(default)
}

/// Returns how many decisive greedy tokens a run must compare.
fn minimum_greedy() -> usize {
    std::env::var("TRANSFORMERS_GEMMA_MIN_GREEDY")
        .map(|value| value.parse().expect("minimum must be an integer"))
        .unwrap_or(DEFAULT_MIN_GREEDY)
}

/// Loads the checkpoint and the short-prompt bundle.
fn load<B: Backend>(device: &B::Device) -> (AutoCausalLm<B>, Reference, f32) {
    load_bundle(&directory("TRANSFORMERS_GEMMA_REFERENCE_DIR"), device)
}

/// Loads the checkpoint with F32 casts after checking it matches the bundle in `reference_dir`.
///
/// A multimodal checkpoint must report its vision tower, and nothing else,
/// as intentionally ignored.
fn load_bundle<B: Backend>(
    reference_dir: &Path,
    device: &B::Device,
) -> (AutoCausalLm<B>, Reference, f32) {
    let model_dir = directory("TRANSFORMERS_GEMMA_DIR");
    let tolerance = tolerance();
    let reference = Reference::read(reference_dir);
    let config = std::fs::read(model_dir.join("config.json")).unwrap();
    assert_eq!(
        hex(&Sha256::digest(&config)),
        reference.config_sha256,
        "the bundle was generated from another config.json"
    );
    let options = AutoLoadOptions {
        checkpoint: LoadOptions {
            dtype_policy: DTypePolicy::Cast(TensorDType::F32),
            ..LoadOptions::default()
        },
        load_tokenizer: false,
        ..AutoLoadOptions::default()
    };
    let loaded = AutoCausalLm::<B>::load_local(&model_dir, &options, device).expect("strict load");
    let ignored = &loaded.load_report().allowlisted_ignored;
    assert!(
        ignored.iter().all(|name| {
            [
                "vision_tower.",
                "multi_modal_projector.",
                "model.vision_tower.",
                "model.multi_modal_projector.",
            ]
            .iter()
            .any(|prefix| name.starts_with(prefix))
        }),
        "only vision-tower tensors may be ignored"
    );
    eprintln!(
        "load: {} vision-tower tensors intentionally ignored",
        ignored.len()
    );
    let model = loaded.into_model();
    assert_eq!(model.config().vocabulary_size(), reference.vocabulary);
    (model, reference, tolerance)
}

/// Uploads one row of token IDs.
fn row<B: Backend>(tokens: &[i64], device: &B::Device) -> Tensor<B, 2, Int> {
    Tensor::from_data(TensorData::new(tokens.to_vec(), [1, tokens.len()]), device)
}

/// Reads logits to the host as F32.
fn host<B: Backend, const D: usize>(tensor: Tensor<B, D>) -> Vec<f32> {
    tensor
        .cast(burn::tensor::DType::F32)
        .into_data()
        .to_vec::<f32>()
        .unwrap()
}

/// Returns the largest absolute difference.
fn gap(actual: &[f32], expected: &[f32]) -> f32 {
    actual
        .iter()
        .zip(expected)
        .map(|(a, e)| (a - e).abs())
        .fold(0.0, f32::max)
}

/// Returns the argmax.
fn argmax(logits: &[f32]) -> usize {
    (0..logits.len())
        .max_by(|&a, &b| logits[a].total_cmp(&logits[b]).then(b.cmp(&a)))
        .unwrap()
}

/// Stateless logits at every prompt position match the reference.
fn check_prompt_logits<B: Backend>(device: &B::Device) {
    let (model, reference, tolerance) = load::<B>(device);
    let options = ForwardOptions {
        logits: LogitsSelection::All,
        ..ForwardOptions::default()
    };
    for (index, prompt) in reference.prompts.iter().enumerate() {
        let input = CausalLmInput {
            token_ids: row::<B>(&prompt.tokens, device),
            token_mask: None,
            position_ids: None,
        };
        let logits = host(model.forward(input, &options).unwrap().logits);
        let largest = gap(&logits, &prompt.logits);
        eprintln!(
            "prompt {index}: {} tokens, max |Δ| = {largest:e}",
            prompt.tokens.len()
        );
        assert!(
            largest <= tolerance,
            "prompt {index}: max |Δ| = {largest:e}"
        );
    }
}

/// The cached greedy continuation of prompt 0 matches while it is decisive.
fn check_cached_greedy<B: Backend>(device: &B::Device) {
    let (model, reference, tolerance) = load::<B>(device);
    let prompt = &reference.prompts[0];
    let capacity = prompt.tokens.len() + reference.greedy.len();
    let mut state = model
        .new_decode_state(CacheConfig::new(1, capacity).unwrap(), 1, device)
        .unwrap();
    let input = CausalLmInput {
        token_ids: row::<B>(&prompt.tokens, device),
        token_mask: None,
        position_ids: None,
    };
    let mut logits = host(
        model
            .prefill(input, &mut state, &ForwardOptions::default())
            .unwrap()
            .logits,
    );
    let last = &prompt.logits[(prompt.tokens.len() - 1) * reference.vocabulary..];
    let prefill_gap = gap(&logits, last);
    eprintln!("cached prefill: max |Δ| = {prefill_gap:e}");
    assert!(prefill_gap <= tolerance, "cached prefill logits");
    let mut compared = 0;
    for (step, &(expected, margin)) in reference.greedy.iter().enumerate() {
        if margin <= 2.0 * tolerance {
            eprintln!("greedy step {step}: reference margin {margin:e} is a tie; stopping");
            break;
        }
        compared += 1;
        assert_eq!(argmax(&logits) as i64, expected, "greedy step {step}");
        let next = DecodeInput {
            token_ids: row::<B>(&[expected], device),
            position_ids: None,
            token_mask: None,
        };
        logits = host(
            model
                .decode(next, &mut state, &ForwardOptions::default())
                .unwrap()
                .logits,
        );
    }
    eprintln!(
        "greedy: {compared} of {} tokens match",
        reference.greedy.len()
    );
    let minimum = minimum_greedy().min(reference.greedy.len());
    assert!(
        compared >= minimum,
        "only {compared} decisive greedy tokens were compared (minimum {minimum}); \
         regenerate the bundle with another first prompt or lower TRANSFORMERS_GEMMA_MIN_GREEDY"
    );
}

/// All prompts in one left-padded batch reproduce each prompt's last logits.
fn check_batched_prefill<B: Backend>(device: &B::Device) {
    let (model, reference, tolerance) = load::<B>(device);
    let width = reference
        .prompts
        .iter()
        .map(|prompt| prompt.tokens.len())
        .max()
        .unwrap();
    let rows = reference.prompts.len();
    let mut tokens = Vec::with_capacity(rows * width);
    let mut valid = Vec::with_capacity(rows * width);
    for prompt in &reference.prompts {
        let padding = width - prompt.tokens.len();
        tokens.extend(std::iter::repeat_n(0, padding).chain(prompt.tokens.iter().copied()));
        valid.extend(
            std::iter::repeat_n(0_i64, padding).chain(std::iter::repeat_n(1, prompt.tokens.len())),
        );
    }
    let token_mask =
        Tensor::<B, 2, Int>::from_data(TensorData::new(valid, [rows, width]), device).equal_elem(1);
    let mut state = model
        .new_decode_state(CacheConfig::new(rows, width).unwrap(), rows, device)
        .unwrap();
    let input = CausalLmInput {
        token_ids: Tensor::from_data(TensorData::new(tokens, [rows, width]), device),
        token_mask: Some(TokenMask::new(token_mask)),
        position_ids: None,
    };
    let logits = host(
        model
            .prefill(input, &mut state, &ForwardOptions::default())
            .unwrap()
            .logits,
    );
    for (index, prompt) in reference.prompts.iter().enumerate() {
        let actual = &logits[index * reference.vocabulary..(index + 1) * reference.vocabulary];
        let expected = &prompt.logits[(prompt.tokens.len() - 1) * reference.vocabulary..];
        let largest = gap(actual, expected);
        eprintln!("batched row {index}: max |Δ| = {largest:e}");
        assert!(largest <= tolerance, "batched row {index}");
    }
}

/// Loads the long-context bundle and returns the model, bundle, long tolerance, and sliding window.
fn load_long<B: Backend>(device: &B::Device) -> (AutoCausalLm<B>, Reference, f32, usize) {
    let (model, reference, _) =
        load_bundle::<B>(&directory("TRANSFORMERS_GEMMA_LONG_REFERENCE_DIR"), device);
    let tolerance = long_tolerance();
    let AutoCausalLm::Gemma(gemma) = &model else {
        panic!("the checkpoint must load as the Gemma family");
    };
    let window = gemma
        .architecture()
        .sliding_window()
        .expect("the checkpoint has sliding layers");
    let length = reference.prompts[0].tokens.len();
    assert!(
        length >= window + 64,
        "the long prompt ({length} tokens) must cross the {window}-token window"
    );
    (model, reference, tolerance, window)
}

/// Stateless logits at the given prompt positions, as one row per position.
fn logits_at<B: Backend>(
    model: &AutoCausalLm<B>,
    tokens: &[i64],
    positions: &[usize],
    device: &B::Device,
) -> Vec<f32> {
    let input = CausalLmInput {
        token_ids: row::<B>(tokens, device),
        token_mask: None,
        position_ids: None,
    };
    let options = ForwardOptions {
        logits: LogitsSelection::Positions(positions.to_vec()),
        ..ForwardOptions::default()
    };
    host(model.forward(input, &options).unwrap().logits)
}

/// Largest gaps to the reference by position range around the window.
struct WindowGaps {
    /// Positions before the window, where every key is visible to sliding layers.
    before: f32,
    /// The first eight positions at and after the window, the first to lose a key.
    boundary: f32,
    /// Every position at or beyond the window.
    beyond: f32,
}

/// Measures the gaps to the reference before, at, and beyond the window.
///
/// Also prints the largest gap per position range, so a step at the window
/// boundary (a semantic error) is distinguishable from the smooth drift of
/// F32 accumulation.
fn gaps_around_window(
    logits: &[f32],
    reference: &Reference,
    positions: &[usize],
    window: usize,
    label: &str,
) -> WindowGaps {
    let vocabulary = reference.vocabulary;
    let prompt = &reference.prompts[0];
    let gaps: Vec<(usize, f32)> = positions
        .iter()
        .enumerate()
        .map(|(index, &position)| {
            let actual = &logits[index * vocabulary..(index + 1) * vocabulary];
            let expected = &prompt.logits[position * vocabulary..(position + 1) * vocabulary];
            (position, gap(actual, expected))
        })
        .collect();
    let largest = |range: std::ops::Range<usize>| {
        gaps.iter()
            .filter(|(position, _)| range.contains(position))
            .map(|&(_, gap)| gap)
            .fold(0.0_f32, f32::max)
    };
    let end = prompt.tokens.len();
    for range in [
        0..4,
        window - 8..window,
        window..window + 8,
        window + 8..window + 64,
        window + 64..end,
    ] {
        eprintln!(
            "{label}: positions {range:?}: max |Δ| = {:e}",
            largest(range.clone())
        );
    }
    WindowGaps {
        before: largest(0..window),
        boundary: largest(window..window + 8),
        beyond: largest(window..end),
    }
}

/// Stateless logits on both sides of the sliding window, and the window's decisiveness.
///
/// Checks the first positions and every position from eight before the
/// window to the end of the prompt. Then every sliding layer is made
/// global: positions before the window must still match (their window
/// already covers the whole prefix), while positions from the very first
/// one at the window onward must leave the tolerance at least tenfold,
/// proving this bundle detects a missing or misplaced window.
fn check_long_context_logits<B: Backend>(device: &B::Device) {
    let (mut model, reference, tolerance, window) = load_long::<B>(device);
    let tokens = &reference.prompts[0].tokens;
    let positions: Vec<usize> = (0..4).chain(window - 8..tokens.len()).collect();
    let logits = logits_at(&model, tokens, &positions, device);
    let windowed = gaps_around_window(&logits, &reference, &positions, window, "windowed");
    eprintln!(
        "long prompt ({} tokens, window {window}): max |Δ| = {:e} before the window, {:e} at or beyond it",
        tokens.len(),
        windowed.before,
        windowed.beyond
    );
    assert!(windowed.before <= tolerance, "logits before the window");
    assert!(
        windowed.beyond <= tolerance,
        "logits at and beyond the window"
    );

    let AutoCausalLm::Gemma(gemma) = &mut model else {
        unreachable!("checked by load_long");
    };
    for layer in &mut gemma.model.layers {
        if matches!(
            layer.schedule.connectivity,
            AttentionConnectivity::SlidingWindow { .. }
        ) {
            layer.schedule.connectivity = AttentionConnectivity::Global;
        }
    }
    let unwindowed = logits_at(&model, tokens, &positions, device);
    let unwindowed = gaps_around_window(&unwindowed, &reference, &positions, window, "unwindowed");
    assert!(
        unwindowed.before <= tolerance,
        "positions before the window cannot depend on it"
    );
    assert!(
        unwindowed.boundary > 10.0 * tolerance,
        "the long bundle must detect a missing window from its first position (max |Δ| {:e})",
        unwindowed.boundary
    );
}

/// A cached run whose sliding layers live in wrapping rings, then the greedy continuation.
///
/// The capacity (prompt plus continuation) exceeds the window, so sliding
/// layers are stored in rings of `window` slots. The first prefill chunk
/// stops 24 tokens before the window; the second appends the rest of the
/// prompt in one step, wrapping every ring while its queries read the
/// evicted range's successors. Both chunks' last logits and every decisive
/// greedy token must match the reference.
fn check_long_context_cached<B: Backend>(device: &B::Device) {
    let (model, reference, tolerance, window) = load_long::<B>(device);
    let prompt = &reference.prompts[0];
    let vocabulary = reference.vocabulary;
    let length = prompt.tokens.len();
    let capacity = length + reference.greedy.len();
    let mut state = model
        .new_decode_state(CacheConfig::new(1, capacity).unwrap(), 1, device)
        .unwrap();
    let AutoCausalDecodeState::Gemma(gemma_state) = &state else {
        panic!("a Gemma model allocates a Gemma decode state");
    };
    let rings = gemma_state.ring_layers();
    eprintln!("cached: capacity {capacity}, {rings} layers in {window}-slot rings");
    assert!(rings > 0, "sliding layers below the capacity live in rings");
    let split = window - 24;
    let mut logits = Vec::new();
    for range in [0..split, split..length] {
        let input = CausalLmInput {
            token_ids: row::<B>(&prompt.tokens[range.clone()], device),
            token_mask: None,
            position_ids: None,
        };
        logits = host(
            model
                .prefill(input, &mut state, &ForwardOptions::default())
                .unwrap()
                .logits,
        );
        let last = range.end - 1;
        let largest = gap(
            &logits,
            &prompt.logits[last * vocabulary..(last + 1) * vocabulary],
        );
        eprintln!("cached chunk {range:?}: max |Δ| = {largest:e} at position {last}");
        assert!(largest <= tolerance, "cached chunk {range:?}");
    }
    let mut compared = 0;
    for (step, &(expected, margin)) in reference.greedy.iter().enumerate() {
        if margin <= 2.0 * tolerance {
            eprintln!("greedy step {step}: reference margin {margin:e} is a tie; stopping");
            break;
        }
        assert_eq!(argmax(&logits) as i64, expected, "greedy step {step}");
        compared += 1;
        let next = DecodeInput {
            token_ids: row::<B>(&[expected], device),
            position_ids: None,
            token_mask: None,
        };
        logits = host(
            model
                .decode(next, &mut state, &ForwardOptions::default())
                .unwrap()
                .logits,
        );
    }
    eprintln!(
        "long greedy: {compared} of {} tokens match",
        reference.greedy.len()
    );
    let minimum = minimum_greedy().min(reference.greedy.len());
    assert!(
        compared >= minimum,
        "only {compared} decisive greedy tokens"
    );
}

