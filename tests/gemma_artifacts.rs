/// Default absolute logit tolerance; see the module documentation.
const DEFAULT_TOLERANCE: f32 = 1e-3;

/// Default absolute logit tolerance of the long-context bundle; see the module documentation.
const DEFAULT_LONG_TOLERANCE: f32 = 5e-3;

/// Default minimum number of decisive greedy tokens that must be compared.
const DEFAULT_MIN_GREEDY: usize = 2;

/// One prompt of the reference bundle.
struct Prompt {
    /// Token IDs of the unpadded prompt.
    tokens: Vec<i64>,
    /// Row-major `[tokens, vocabulary]` logits.
    logits: Vec<f32>,
}

/// A parsed reference bundle.
struct Reference {
    /// Vocabulary size `V`.
    vocabulary: usize,
    /// Prompts in bundle order.
    prompts: Vec<Prompt>,
    /// Greedy continuation of prompt 0 as `(token, margin)`.
    greedy: Vec<(i64, f32)>,
    /// SHA-256 of the configuration the bundle was generated from.
    config_sha256: String,
}

impl Reference {
    /// Reads and checks a bundle directory.
    fn read(root: &Path) -> Self {
        let manifest: Value =
            serde_json::from_str(&std::fs::read_to_string(root.join("reference.json")).unwrap())
                .unwrap();
        let vocabulary = manifest["vocabulary_size"].as_u64().unwrap() as usize;
        let prompts = manifest["prompts"]
            .as_array()
            .unwrap()
            .iter()
            .map(|prompt| {
                let tokens: Vec<i64> = serde_json::from_value(prompt["token_ids"].clone()).unwrap();
                let file = root.join(prompt["logits_file"].as_str().unwrap());
                let bytes = std::fs::read(&file).unwrap();
                assert_eq!(
                    hex(&Sha256::digest(&bytes)),
                    prompt["logits_sha256"].as_str().unwrap(),
                    "{} is corrupted",
                    file.display()
                );
                let logits: Vec<f32> = bytes
                    .as_chunks::<4>()
                    .0
                    .iter()
                    .map(|chunk| f32::from_le_bytes(*chunk))
                    .collect();
                assert_eq!(logits.len(), tokens.len() * vocabulary);
                Prompt { tokens, logits }
            })
            .collect();
        let greedy = manifest["greedy"]["steps"]
            .as_array()
            .unwrap()
            .iter()
            .map(|step| {
                (
                    step["token"].as_i64().unwrap(),
                    step["margin"].as_f64().unwrap() as f32,
                )
            })
            .collect();
        Self {
            vocabulary,
            prompts,
            greedy,
            config_sha256: manifest["provenance"]["config_sha256"]
                .as_str()
                .unwrap()
                .into(),
        }
    }
}

/// Lower-case hexadecimal digest.
fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

/// The environment variables naming one truth bundle and what judges runs against it.
struct BundleVariables {
    /// The F32 truth bundle.
    reference: &'static str,
    /// The truth's F32 CPU-eager decode truth.
    decode_truth: &'static str,
    /// The four official BF16 graphs (half-precision runs only).
    official: &'static str,
    /// The four official F16 graphs, read only to show that no F16 envelope exists.
    official_f16: &'static str,
}

/// Variables of the short-prompt bundle.
const SHORT: BundleVariables = BundleVariables {
    reference: "TRANSFORMERS_GEMMA_REFERENCE_DIR",
    decode_truth: "TRANSFORMERS_GEMMA_DECODE_TRUTH_DIR",
    official: "TRANSFORMERS_GEMMA_OFFICIAL_DIRS",
    official_f16: "TRANSFORMERS_GEMMA_F16_OFFICIAL_DIRS",
};

/// Variables of the long-context bundle.
const LONG: BundleVariables = BundleVariables {
    reference: "TRANSFORMERS_GEMMA_LONG_REFERENCE_DIR",
    decode_truth: "TRANSFORMERS_GEMMA_LONG_DECODE_TRUTH_DIR",
    official: "TRANSFORMERS_GEMMA_LONG_OFFICIAL_DIRS",
    official_f16: "TRANSFORMERS_GEMMA_LONG_F16_OFFICIAL_DIRS",
};

/// Variables of the previous single-bundle half-precision rule, and what replaces each.
const RETIRED: [(&str, &str); 2] = [
    (
        "TRANSFORMERS_GEMMA_BF16_REFERENCE_DIR",
        "TRANSFORMERS_GEMMA_OFFICIAL_DIRS and TRANSFORMERS_GEMMA_DECODE_TRUTH_DIR",
    ),
    (
        "TRANSFORMERS_GEMMA_LONG_BF16_REFERENCE_DIR",
        "TRANSFORMERS_GEMMA_LONG_OFFICIAL_DIRS and TRANSFORMERS_GEMMA_LONG_DECODE_TRUTH_DIR",
    ),
];

/// Refuses an F16 run: Gemma 3 has no F16 gate profile.
///
/// # Panics
///
/// If `dtype` is F16; see the module documentation's [F16](self#f16) section.
fn refuse_f16(dtype: TensorDType) {
    assert!(
        dtype != TensorDType::F16,
        "TRANSFORMERS_GEMMA_DTYPE=f16 is not a gate profile: gemma-3-4b-it overflows F16 in \
         Transformers' own CPU and MPS F16 graphs too (block 5's post-MLP residual add at BOS reaches \
         73,509.6 > 65,504), so no official F16 envelope exists; qualify Metal in F32 and half \
         precision in bf16 (see tests/gemma_artifacts.rs, F16, and \
         acceptance/measurements/half-precision-envelope-20261018.json)"
    );
}

/// Returns the directory named by the environment variable `name`.
fn directory(name: &str) -> PathBuf {
    std::env::var_os(name)
        .map(PathBuf::from)
        .unwrap_or_else(|| panic!("set {name}; see the module documentation"))
}

/// Returns the absolute logit tolerance: `TRANSFORMERS_GEMMA_TOLERANCE` or [`DEFAULT_TOLERANCE`].
///
/// The default applies only to a device of F32 `precision`.
fn tolerance(precision: MatmulPrecision) -> f32 {
    checkpoint_tolerance("TRANSFORMERS_GEMMA_TOLERANCE", DEFAULT_TOLERANCE, precision)
}

/// Returns the long-context tolerance: `TRANSFORMERS_GEMMA_LONG_TOLERANCE` or [`DEFAULT_LONG_TOLERANCE`].
///
/// The default applies only to a device of F32 `precision`.
fn long_tolerance(precision: MatmulPrecision) -> f32 {
    checkpoint_tolerance(
        "TRANSFORMERS_GEMMA_LONG_TOLERANCE",
        DEFAULT_LONG_TOLERANCE,
        precision,
    )
}

/// Returns how many decisive greedy tokens a run must compare.
fn minimum_greedy() -> usize {
    std::env::var("TRANSFORMERS_GEMMA_MIN_GREEDY")
        .map(|value| value.parse().expect("minimum must be an integer"))
        .unwrap_or(DEFAULT_MIN_GREEDY)
}

/// A loaded checkpoint, its bundle, its greedy tolerance, and the gate of an F16 or BF16 run.
///
/// The tolerance decides greedy steps ([`check_teacher_forced_greedy`]). In
/// an F32 run it is the bundle's absolute logit tolerance and also judges
/// every logit; in a half-precision run it is the gate's greedy bound
/// ([`HalfPrecisionGate::greedy_tolerance`]), and the gate judges the logits.
type Loaded<B> = (AutoCausalLm<B>, Reference, f32, Option<HalfPrecisionGate>);

/// Loads the checkpoint and the short-prompt bundle.
fn load<B: Backend>(device: &B::Device) -> Loaded<B> {
    load_bundle(&SHORT, tolerance, device)
}

/// Loads the checkpoint in `TRANSFORMERS_GEMMA_DTYPE` after checking it matches the bundle `variables` names.
///
/// A multimodal checkpoint must report its vision tower, and nothing else,
/// as intentionally ignored. The retired single-bundle variables and an F16
/// run are refused first. The device is then probed. An F32 run (the
/// default) takes the tolerance `f32_tolerance` resolves from the probe, so a
/// TF32 device without an explicit tolerance fails before loading. A BF16 run
/// refuses both F32 tolerance overrides on every device and is judged by the
/// official envelope of the bundles `variables` names, which is validated
/// before the checkpoint loads. Either run then prints one line with the
/// probe's finding and what judges the run: the F32 tolerance, or, in half
/// precision, the official envelope and its greedy tolerance, so a
/// half-precision log states that the probe was not applied.
fn load_bundle<B: Backend>(
    variables: &BundleVariables,
    f32_tolerance: fn(MatmulPrecision) -> f32,
    device: &B::Device,
) -> Loaded<B> {
    refuse_retired(&RETIRED);
    let dtype = run_dtype("TRANSFORMERS_GEMMA_DTYPE");
    refuse_f16(dtype);
    let reference_dir = directory(variables.reference);
    let precision = MatmulPrecision::probe::<B>(device);
    let (tolerance, half) = if is_half_precision(dtype) {
        reject_overrides(&[
            "TRANSFORMERS_GEMMA_TOLERANCE",
            "TRANSFORMERS_GEMMA_LONG_TOLERANCE",
        ]);
        let half = HalfPrecisionGate::new(
            dtype,
            &reference_dir,
            &directory(variables.decode_truth),
            &required_directories(variables.official),
        );
        let tolerance = half.greedy_tolerance();
        eprintln!(
            "F32 matrix products use {precision:?} inputs; the {dtype:?} run is judged by the official envelope, greedy steps at {tolerance:e}"
        );
        (tolerance, Some(half))
    } else {
        let tolerance = f32_tolerance(precision);
        eprintln!("F32 matrix products use {precision:?} inputs; tolerance {tolerance:e}");
        (tolerance, None)
    };
    let model_dir = directory("TRANSFORMERS_GEMMA_DIR");
    let reference = Reference::read(&reference_dir);
    let config = std::fs::read(model_dir.join("config.json")).unwrap();
    assert_eq!(
        hex(&Sha256::digest(&config)),
        reference.config_sha256,
        "the bundle was generated from another config.json"
    );
    let options = AutoLoadOptions {
        checkpoint: LoadOptions {
            dtype_policy: DTypePolicy::Cast(dtype),
            ..LoadOptions::default()
        },
        load_tokenizer: false,
        ..AutoLoadOptions::default()
    };
    let loaded = AutoCausalLm::<B>::load_local(&model_dir, &options, device).expect("strict load");
    let ignored = &loaded.load_report().allowlisted_ignored;
    assert!(
        ignored.iter().all(|name| {
            [
                "vision_tower.",
                "multi_modal_projector.",
                "model.vision_tower.",
                "model.multi_modal_projector.",
            ]
            .iter()
            .any(|prefix| name.starts_with(prefix))
        }),
        "only vision-tower tensors may be ignored"
    );
    eprintln!(
        "load: {} vision-tower tensors intentionally ignored",
        ignored.len()
    );
    let model = loaded.into_model();
    assert_eq!(model.config().vocabulary_size(), reference.vocabulary);
    (model, reference, tolerance, half)
}

/// Uploads one row of token IDs.
fn row<B: Backend>(tokens: &[i64], device: &B::Device) -> Tensor<B, 2, Int> {
    Tensor::from_data(TensorData::new(tokens.to_vec(), [1, tokens.len()]), device)
}

/// Reads logits to the host as F32.
fn host<B: Backend, const D: usize>(tensor: Tensor<B, D>) -> Vec<f32> {
    tensor
        .cast(burn::tensor::DType::F32)
        .into_data()
        .to_vec::<f32>()
        .unwrap()
}

/// Returns the stateless last-position logits of one unpadded prompt.
fn last_logits<B: Backend>(
    model: &AutoCausalLm<B>,
    tokens: &[i64],
    device: &B::Device,
) -> Vec<f32> {
    let input = CausalLmInput {
        token_ids: row::<B>(tokens, device),
        token_mask: None,
        position_ids: None,
    };
    host(
        model
            .forward(input, &ForwardOptions::default())
            .unwrap()
            .logits,
    )
}

/// Returns the largest absolute difference of two equally long sets of logits.
///
/// A non-finite value on either side counts as an infinite difference, so a
/// NaN or infinite logit fails every tolerance (see [`Gap::measure`], which
/// also rejects a length mismatch).
fn gap(actual: &[f32], expected: &[f32]) -> f32 {
    Gap::measure(actual, expected).deviation
}

/// Stateless logits at every prompt position match the reference.
fn check_prompt_logits<B: Backend>(device: &B::Device) {
    let (model, reference, tolerance, half) = load::<B>(device);
    let options = ForwardOptions {
        logits: LogitsSelection::All,
        ..ForwardOptions::default()
    };
    for (index, prompt) in reference.prompts.iter().enumerate() {
        let input = CausalLmInput {
            token_ids: row::<B>(&prompt.tokens, device),
            token_mask: None,
            position_ids: None,
        };
        let logits = host(model.forward(input, &options).unwrap().logits);
        if let Some(half) = &half {
            half.check_prompt(&format!("prompt {index}"), index, &logits, &prompt.logits);
            continue;
        }
        let largest = gap(&logits, &prompt.logits);
        eprintln!(
            "prompt {index}: {} tokens, max |Δ| = {largest:e}",
            prompt.tokens.len()
        );
        assert!(
            largest <= tolerance,
            "prompt {index}: max |Δ| = {largest:e}"
        );
    }
}

/// The cached greedy continuation of prompt 0 matches at every decisive step, and its decode rows match the decode truth.
///
/// The reference's tokens are fed back, so ties are skipped rather than
/// ending the comparison; see [`check_teacher_forced_greedy`], which decides
/// an F32 run's steps at its tolerance and a half-precision run's at the
/// gate's greedy bound. Whatever the margins, every decode row is also judged
/// against the decode truth in `TRANSFORMERS_GEMMA_DECODE_TRUTH_DIR`: an F32
/// run's cached rows at its tolerance ([`DecodeTruth::check_f32`]), a
/// half-precision run's cached rows and its stateless rows at the same
/// positions by the official decode envelope
/// ([`HalfPrecisionGate::check_decode`]). A half-precision run also checks
/// the prefill against the stateless pass (provisionally) and the longest
/// prompt decoded token by token ([`check_cached_prompt_decode`]).
fn check_cached_greedy<B: Backend>(device: &B::Device) {
    let (model, reference, tolerance, half) = load::<B>(device);
    let f32_truth = half
        .is_none()
        .then(|| DecodeTruth::read(&directory(SHORT.reference), &directory(SHORT.decode_truth)));
    let prompt = &reference.prompts[0];
    let capacity = prompt.tokens.len() + reference.greedy.len();
    let mut state = model
        .new_decode_state(CacheConfig::new(1, capacity).unwrap(), 1, device)
        .unwrap();
    let input = CausalLmInput {
        token_ids: row::<B>(&prompt.tokens, device),
        token_mask: None,
        position_ids: None,
    };
    let logits = host(
        model
            .prefill(input, &mut state, &ForwardOptions::default())
            .unwrap()
            .logits,
    );
    let last = &prompt.logits[(prompt.tokens.len() - 1) * reference.vocabulary..];
    match &half {
        None => {
            let prefill_gap = gap(&logits, last);
            eprintln!("cached prefill: max |Δ| = {prefill_gap:e}");
            assert!(prefill_gap <= tolerance, "cached prefill logits");
        }
        Some(half) => {
            half.check_rows("cached prefill", 0, &logits, last);
            let stateless = last_logits(&model, &prompt.tokens, device);
            half.check_consistency("cached prefill", &logits, &stateless);
        }
    }
    // Every decode step's logits are kept for the decode-row checks below.
    let mut decoded = Vec::new();
    let mut decode = |token| {
        let logits = decode_one(&model, &mut state, token, device);
        decoded.push(logits.clone());
        logits
    };
    check_teacher_forced_greedy(
        "greedy",
        &reference.greedy,
        tolerance,
        minimum_greedy(),
        "TRANSFORMERS_GEMMA_MIN_GREEDY",
        logits,
        &mut decode,
    );
    // The comparison decodes no token after its last step; decoding the last
    // greedy token too gives every token of the continuation one decode step,
    // and decode step s, fed greedy token s at position T + s, returns the
    // logits of that position, the decode truth's row s.
    let Some(&(token, _)) = reference.greedy.last() else {
        panic!("the bundle's greedy continuation is empty, so no decode step can be checked");
    };
    decode(token);
    let Some(half) = &half else {
        f32_truth
            .expect("an F32 run reads the decode truth")
            .check_f32("cached decode", &decoded, tolerance);
        return;
    };
    let continued = continued_prompt(&reference);
    let positions: Vec<usize> = (prompt.tokens.len()..continued.len()).collect();
    let stateless = logits_at(&model, &continued, &positions, device);
    half.check_decode("cached decode", prompt.tokens.len(), &decoded, &stateless);
    check_cached_prompt_decode(&model, &reference, half, device);
}

/// Appends one token to `state` and returns the logits of its position.
fn decode_one<B: Backend>(
    model: &AutoCausalLm<B>,
    state: &mut AutoCausalDecodeState<B>,
    token: i64,
    device: &B::Device,
) -> Vec<f32> {
    let next = DecodeInput {
        token_ids: row::<B>(&[token], device),
        position_ids: None,
        token_mask: None,
    };
    host(
        model
            .decode(next, state, &ForwardOptions::default())
            .unwrap()
            .logits,
    )
}

/// Returns prompt 0 followed by the bundle's teacher-forced greedy tokens.
fn continued_prompt(reference: &Reference) -> Vec<i64> {
    reference.prompts[0]
        .tokens
        .iter()
        .copied()
        .chain(reference.greedy.iter().map(|&(token, _)| token))
        .collect()
}

/// Decodes the longest prompt token by token after a prefill of its first quarter and judges it by the official prompt-decode envelope.
///
/// The prompt and the prefill length are the ones the official graphs used
/// ([`HalfPrecisionGate::prompt_decode_plan`]). The prefill returns the
/// logits of each of its positions and every later position comes from one
/// cached decode step, so the assembled `[tokens, V]` logits cover the whole
/// prompt and must meet both bounds of the official graphs' own cached decode
/// under the same protocol, as gpt-oss's `check_cached_long_prompt` bounds its
/// decode path against the bundle itself. The short prompts stay below the
/// sliding window, so no ring wraps here (the long-context test covers that).
fn check_cached_prompt_decode<B: Backend>(
    model: &AutoCausalLm<B>,
    reference: &Reference,
    half: &HalfPrecisionGate,
    device: &B::Device,
) {
    let (index, prefill) = half.prompt_decode_plan();
    let prompt = &reference.prompts[index];
    let length = prompt.tokens.len();
    let mut state = model
        .new_decode_state(CacheConfig::new(1, length).unwrap(), 1, device)
        .unwrap();
    let every_position = ForwardOptions {
        logits: LogitsSelection::All,
        ..ForwardOptions::default()
    };
    let input = CausalLmInput {
        token_ids: row::<B>(&prompt.tokens[..prefill], device),
        token_mask: None,
        position_ids: None,
    };
    let mut logits = host(
        model
            .prefill(input, &mut state, &every_position)
            .unwrap()
            .logits,
    );
    for &token in &prompt.tokens[prefill..] {
        logits.extend(decode_one(model, &mut state, token, device));
    }
    half.check_prompt_decode(
        &format!("prompt {index} decoded after a {prefill}-token prefill"),
        &logits,
        &prompt.logits,
    );
}

/// All prompts in one left-padded batch reproduce each prompt's last logits.
///
/// A half-precision run also checks each row against the stateless pass.
fn check_batched_prefill<B: Backend>(device: &B::Device) {
    let (model, reference, tolerance, half) = load::<B>(device);
    let width = reference
        .prompts
        .iter()
        .map(|prompt| prompt.tokens.len())
        .max()
        .unwrap();
    let rows = reference.prompts.len();
    let mut tokens = Vec::with_capacity(rows * width);
    let mut valid = Vec::with_capacity(rows * width);
    for prompt in &reference.prompts {
        let padding = width - prompt.tokens.len();
        tokens.extend(std::iter::repeat_n(0, padding).chain(prompt.tokens.iter().copied()));
        valid.extend(
            std::iter::repeat_n(0_i64, padding).chain(std::iter::repeat_n(1, prompt.tokens.len())),
        );
    }
    let token_mask =
        Tensor::<B, 2, Int>::from_data(TensorData::new(valid, [rows, width]), device).equal_elem(1);
    let mut state = model
        .new_decode_state(CacheConfig::new(rows, width).unwrap(), rows, device)
        .unwrap();
    let input = CausalLmInput {
        token_ids: Tensor::from_data(TensorData::new(tokens, [rows, width]), device),
        token_mask: Some(TokenMask::new(token_mask)),
        position_ids: None,
    };
    let logits = host(
        model
            .prefill(input, &mut state, &ForwardOptions::default())
            .unwrap()
            .logits,
    );
    for (index, prompt) in reference.prompts.iter().enumerate() {
        let actual = &logits[index * reference.vocabulary..(index + 1) * reference.vocabulary];
        let expected = &prompt.logits[(prompt.tokens.len() - 1) * reference.vocabulary..];
        if let Some(half) = &half {
            let label = format!("batched row {index}");
            let alone = last_logits(&model, &prompt.tokens, device);
            half.check_consistency(&label, actual, &alone);
            half.check_rows(&label, index, actual, expected);
            continue;
        }
        let largest = gap(actual, expected);
        eprintln!("batched row {index}: max |Δ| = {largest:e}");
        assert!(largest <= tolerance, "batched row {index}");
    }
}

/// A loaded long-context checkpoint and bundle, its greedy tolerance, the sliding window, and the half-precision gate.
///
/// The tolerance is as in [`Loaded`] for the long-context bundle: the long
/// F32 tolerance, or at half precision the long prompt's maximum bound.
type LoadedLong<B> = (
    AutoCausalLm<B>,
    Reference,
    f32,
    usize,
    Option<HalfPrecisionGate>,
);

/// Loads the long-context bundle and returns the model, bundle, tolerance, sliding window, and gate.
fn load_long<B: Backend>(device: &B::Device) -> LoadedLong<B> {
    let (model, reference, tolerance, half) = load_bundle::<B>(&LONG, long_tolerance, device);
    let AutoCausalLm::Gemma(gemma) = &model else {
        panic!("the checkpoint must load as the Gemma family");
    };
    let window = gemma
        .architecture()
        .sliding_window()
        .expect("the checkpoint has sliding layers");
    let length = reference.prompts[0].tokens.len();
    assert!(
        length >= window + 64,
        "the long prompt ({length} tokens) must cross the {window}-token window"
    );
    (model, reference, tolerance, window, half)
}

/// Stateless logits at the given prompt positions, as one row per position.
fn logits_at<B: Backend>(
    model: &AutoCausalLm<B>,
    tokens: &[i64],
    positions: &[usize],
    device: &B::Device,
) -> Vec<f32> {
    let input = CausalLmInput {
        token_ids: row::<B>(tokens, device),
        token_mask: None,
        position_ids: None,
    };
    let options = ForwardOptions {
        logits: LogitsSelection::Positions(positions.to_vec()),
        ..ForwardOptions::default()
    };
    host(model.forward(input, &options).unwrap().logits)
}

/// Largest gaps to the reference by position range around the window.
struct WindowGaps {
    /// Positions before the window, where every key is visible to sliding layers.
    before: f32,
    /// The first eight positions at and after the window, the first to lose a key.
    boundary: f32,
    /// Every position at or beyond the window.
    beyond: f32,
}

/// Measures the gaps to the reference before, at, and beyond the window.
///
/// Also prints the largest gap per position range, so a step at the window
/// boundary (a semantic error) is distinguishable from the smooth drift of
/// F32 accumulation.
fn gaps_around_window(
    logits: &[f32],
    reference: &Reference,
    positions: &[usize],
    window: usize,
    label: &str,
) -> WindowGaps {
    let vocabulary = reference.vocabulary;
    let prompt = &reference.prompts[0];
    let gaps: Vec<(usize, f32)> = positions
        .iter()
        .enumerate()
        .map(|(index, &position)| {
            let actual = &logits[index * vocabulary..(index + 1) * vocabulary];
            let expected = &prompt.logits[position * vocabulary..(position + 1) * vocabulary];
            (position, gap(actual, expected))
        })
        .collect();
    let largest = |range: std::ops::Range<usize>| {
        gaps.iter()
            .filter(|(position, _)| range.contains(position))
            .map(|&(_, gap)| gap)
            .fold(0.0_f32, f32::max)
    };
    let end = prompt.tokens.len();
    for range in [
        0..4,
        window - 8..window,
        window..window + 8,
        window + 8..window + 64,
        window + 64..end,
    ] {
        eprintln!(
            "{label}: positions {range:?}: max |Δ| = {:e}",
            largest(range.clone())
        );
    }
    WindowGaps {
        before: largest(0..window),
        boundary: largest(window..window + 8),
        beyond: largest(window..end),
    }
}

/// Stateless logits on both sides of the sliding window, and the window's decisiveness.
///
/// Checks the first positions and every position from eight before the
/// window to the end of the prompt. Then every sliding layer is made
/// global: positions before the window must still match (their window
/// already covers the whole prefix), while positions from the very first
/// one at the window onward must leave the tolerance at least tenfold,
/// proving this bundle detects a missing or misplaced window.
///
/// A half-precision run reads every position, so the prompt's mean is
/// defined as for the official bundle, and must pass the half-precision rule
/// with the window and fail it without (see the module documentation).
fn check_long_context_logits<B: Backend>(device: &B::Device) {
    let (mut model, reference, tolerance, window, half) = load_long::<B>(device);
    let tokens = &reference.prompts[0].tokens;
    let positions: Vec<usize> = match half {
        None => (0..4).chain(window - 8..tokens.len()).collect(),
        Some(_) => (0..tokens.len()).collect(),
    };
    let logits = logits_at(&model, tokens, &positions, device);
    let windowed = gaps_around_window(&logits, &reference, &positions, window, "windowed");
    eprintln!(
        "long prompt ({} tokens, window {window}): max |Δ| = {:e} before the window, {:e} at or beyond it",
        tokens.len(),
        windowed.before,
        windowed.beyond
    );
    match &half {
        None => {
            assert!(windowed.before <= tolerance, "logits before the window");
            assert!(
                windowed.beyond <= tolerance,
                "logits at and beyond the window"
            );
        }
        Some(half) => {
            half.check_prompt("long prompt", 0, &logits, &reference.prompts[0].logits);
        }
    }

    let AutoCausalLm::Gemma(gemma) = &mut model else {
        unreachable!("checked by load_long");
    };
    for layer in &mut gemma.model.layers {
        if matches!(
            layer.schedule.connectivity,
            AttentionConnectivity::SlidingWindow { .. }
        ) {
            layer.schedule.connectivity = AttentionConnectivity::Global;
        }
    }
    let unwindowed_logits = logits_at(&model, tokens, &positions, device);
    let unwindowed = gaps_around_window(
        &unwindowed_logits,
        &reference,
        &positions,
        window,
        "unwindowed",
    );
    let Some(half) = &half else {
        assert!(
            unwindowed.before <= tolerance,
            "positions before the window cannot depend on it"
        );
        assert!(
            unwindowed.boundary > 10.0 * tolerance,
            "the long bundle must detect a missing window from its first position (max |Δ| {:e})",
            unwindowed.boundary
        );
        return;
    };
    let bound = half.bound(0);
    assert!(
        f64::from(unwindowed.before) <= bound.maximum,
        "positions before the window cannot depend on it"
    );
    let missing = Deviation::measure(
        "unwindowed",
        &unwindowed_logits,
        &reference.prompts[0].logits,
    );
    eprintln!(
        "unwindowed: max |Δ| = {:e} (bound {:e}), mean |Δ| = {:e} (bound {:e})",
        missing.maximum, bound.maximum, missing.mean, bound.mean
    );
    assert!(
        !bound.admits(&missing),
        "the half-precision rule must reject the run without the window"
    );
}

/// A cached run whose sliding layers live in wrapping rings, then the greedy continuation.
///
/// The capacity (prompt plus continuation) exceeds the window, so sliding
/// layers are stored in rings of `window` slots. The first prefill chunk
/// stops 24 tokens before the window; the second appends the rest of the
/// prompt in one step, wrapping every ring while its queries read the
/// evicted range's successors. Both chunks' last logits and every decisive
/// greedy token must match the reference.
///
/// Whatever the margins, the 8 decode rows after the wrap are judged against
/// the long decode truth in `TRANSFORMERS_GEMMA_LONG_DECODE_TRUTH_DIR`: an F32
/// run's cached rows at the long tolerance, a half-precision run's cached and
/// stateless rows by the official decode envelope. A half-precision run also
/// applies the long prompt's maximum bound to the chunk ends; that bound is
/// far above what a ring that keeps or evicts the wrong keys moves, so the
/// chunk ends must also agree with the same run's stateless sliding-window
/// pass within the provisional self-consistency tolerance (`0.5`), as the
/// short cached prefill does; the long logits test ties that stateless pass to
/// the bundle.
fn check_long_context_cached<B: Backend>(device: &B::Device) {
    let (model, reference, tolerance, window, half) = load_long::<B>(device);
    let f32_truth = half
        .is_none()
        .then(|| DecodeTruth::read(&directory(LONG.reference), &directory(LONG.decode_truth)));
    let prompt = &reference.prompts[0];
    let vocabulary = reference.vocabulary;
    let length = prompt.tokens.len();
    let capacity = length + reference.greedy.len();
    let split = window - 24;
    // At half precision, one stateless pass over the prompt and the
    // teacher-forced greedy tokens, read at both chunk ends and then at every
    // decoded position (decode step s fed greedy token s at position T + s).
    let judged = half.as_ref().map(|half| {
        let continued = continued_prompt(&reference);
        let positions: Vec<usize> = [split - 1, length - 1]
            .into_iter()
            .chain(length..continued.len())
            .collect();
        (half, logits_at(&model, &continued, &positions, device))
    });
    let mut state = model
        .new_decode_state(CacheConfig::new(1, capacity).unwrap(), 1, device)
        .unwrap();
    let AutoCausalDecodeState::Gemma(gemma_state) = &state else {
        panic!("a Gemma model allocates a Gemma decode state");
    };
    let rings = gemma_state.ring_layers();
    eprintln!("cached: capacity {capacity}, {rings} layers in {window}-slot rings");
    assert!(rings > 0, "sliding layers below the capacity live in rings");
    let mut logits = Vec::new();
    for (chunk, range) in [0..split, split..length].into_iter().enumerate() {
        let input = CausalLmInput {
            token_ids: row::<B>(&prompt.tokens[range.clone()], device),
            token_mask: None,
            position_ids: None,
        };
        logits = host(
            model
                .prefill(input, &mut state, &ForwardOptions::default())
                .unwrap()
                .logits,
        );
        let last = range.end - 1;
        let expected = &prompt.logits[last * vocabulary..(last + 1) * vocabulary];
        if let Some((half, stateless)) = &judged {
            let label = format!("cached chunk {range:?} at position {last}");
            half.check_rows(&label, 0, &logits, expected);
            let alone = &stateless[chunk * vocabulary..(chunk + 1) * vocabulary];
            half.check_consistency(&label, &logits, alone);
            continue;
        }
        let largest = gap(&logits, expected);
        eprintln!("cached chunk {range:?}: max |Δ| = {largest:e} at position {last}");
        assert!(largest <= tolerance, "cached chunk {range:?}");
    }
    // Every decode step's logits are kept for the decode-row checks below.
    let mut decoded = Vec::new();
    let mut decode = |token| {
        let logits = decode_one(&model, &mut state, token, device);
        decoded.push(logits.clone());
        logits
    };
    check_teacher_forced_greedy(
        "long greedy",
        &reference.greedy,
        tolerance,
        minimum_greedy(),
        "TRANSFORMERS_GEMMA_MIN_GREEDY",
        logits,
        &mut decode,
    );
    // As in the short cached test, the last greedy token is decoded too, so
    // every token of the continuation has its decode step.
    let Some(&(token, _)) = reference.greedy.last() else {
        panic!("the long bundle's greedy continuation is empty, so no decode step can be checked");
    };
    decode(token);
    let Some((half, stateless)) = &judged else {
        f32_truth
            .expect("an F32 run reads the long decode truth")
            .check_f32("long cached decode", &decoded, tolerance);
        return;
    };
    half.check_decode(
        "long cached decode",
        length,
        &decoded,
        &stateless[2 * vocabulary..],
    );
}

/// An F16 run is refused before anything loads, naming the measured overflow; BF16 and F32 runs are not.
#[test]
fn f16_runs_are_refused_with_the_measured_overflow() {
    refuse_f16(TensorDType::BF16);
    refuse_f16(TensorDType::F32);
    let refused = std::panic::catch_unwind(|| refuse_f16(TensorDType::F16))
        .expect_err("an F16 run must be refused");
    // A literal assertion message is a `&str` payload, a formatted one a `String`.
    let message = refused
        .downcast_ref::<String>()
        .cloned()
        .or_else(|| {
            refused
                .downcast_ref::<&str>()
                .map(|text| (*text).to_owned())
        })
        .unwrap_or_default();
    for fragment in [
        "TRANSFORMERS_GEMMA_DTYPE=f16 is not a gate profile",
        "73,509.6 > 65,504",
        "no official F16 envelope exists",
        "acceptance/measurements/half-precision-envelope-20261018.json",
    ] {
        assert!(
            message.contains(fragment),
            "{fragment:?} missing from {message:?}"
        );
    }
}

/// Reads the official BF16 envelope of the bundle `variables` names, from the bundles alone.
///
/// # Panics
///
/// If a retired variable is set, the dtype is not BF16, or [`Envelope::read`]
/// refuses the bundles.
fn official_envelope(variables: &BundleVariables) -> Envelope {
    refuse_retired(&RETIRED);
    let dtype = run_dtype("TRANSFORMERS_GEMMA_DTYPE");
    refuse_f16(dtype);
    assert!(
        is_half_precision(dtype),
        "set TRANSFORMERS_GEMMA_DTYPE=bf16 to read the official BF16 envelope"
    );
    Envelope::read(
        dtype,
        &directory(variables.reference),
        &directory(variables.decode_truth),
        &required_directories(variables.official),
    )
}

/// The official BF16 graphs' distance from the short and long truths, which sets the half-precision bounds.
///
/// Reads only the bundles, validates each pairing, and prints each
/// manifest's SHA-256, each official graph's maximum (with its position and
/// vocabulary entry) and mean deviation of every prompt, the decode rows, and
/// the decoded prompt, the envelopes and bounds, and the greedy steps a
/// half-precision run compares. No Burn model runs, so a pass qualifies no
/// Burn run.
#[test]
#[ignore = "needs TRANSFORMERS_GEMMA_DTYPE=bf16 and the short and long _REFERENCE_DIR, _DECODE_TRUTH_DIR, and _OFFICIAL_DIRS (bundles only)"]
fn official_graphs_calibrate_the_half_precision_envelope() {
    for variables in [&SHORT, &LONG] {
        official_envelope(variables).report(&directory(variables.reference));
    }
}

/// Every official BF16 graph lies within the envelope of the other three under the compiled slacks.
