//! Real Gemma checkpoints against locally generated Transformers references.
//!
//! The reference bundle comes from `scripts/generate_causal_lm_reference.py`
//! (Transformers `AutoModelForCausalLM`, F32, CPU, eager attention): token
//! IDs of a few fixed prompts, every prompt position's full-vocabulary
//! logits as raw little-endian F32, and a 32-token cached greedy
//! continuation of the first prompt with each step's top-2 margin. For a
//! multimodal Gemma 3 checkpoint the script runs
//! `Gemma3ForConditionalGeneration` on text-only inputs, which is exactly
//! the text tower this crate executes. These tests are ignored by default
//! and need three local directories:
//!
//! ```text
//! TRANSFORMERS_GEMMA_DIR=/path/to/checkpoint \
//! TRANSFORMERS_GEMMA_REFERENCE_DIR=/path/to/reference-bundle \
//! TRANSFORMERS_GEMMA_LONG_REFERENCE_DIR=/path/to/long-reference-bundle \
//! cargo test --release --test gemma_artifacts -- --ignored --nocapture --test-threads 1
//! ```
//!
//! The long-context bundle holds one prompt longer than the sliding window
//! (see [Long context](#long-context)); only its two tests read it.
//!
//! The pinned acceptance pair is `google/gemma-3-4b-it` at revision
//! `093f9f388b31de276ce2de164bdc2081324b9767` with a bundle generated by
//! Transformers 5.2.0 / PyTorch 2.10.0. Weights are loaded with the strict
//! automatic loader and cast to F32 while streaming (BF16 to F32 is exact,
//! as in the reference); the vision tower's tensors must be reported as
//! intentionally ignored. Each test runs on Flex; with the `metal` feature
//! the same checks also run on Metal in F32. The pairing of checkpoint and
//! bundle is verified through the bundle's SHA-256 of `config.json`. An F32
//! 4B text tower needs about 16 GiB, so run one test at a time.
//!
//! # Tolerance
//!
//! Both sides compute in F32 with different GEMM blockings, so logits drift
//! by accumulated rounding through every layer. Measured on Flex/F32 for the
//! pinned pair (34 layers, vocabulary 262208): prompt logits deviate by at
//! most `7.2e-5`, `1.3e-4`, and `1.6e-4` over 6, 19, and 9 tokens, the
//! left-padded batched prefill by at most `1.1e-4`, and all 32 greedy tokens
//! match. The default absolute tolerance, [`DEFAULT_TOLERANCE`] = `1e-3`,
//! matches the Llama family's real-checkpoint gate and leaves about six
//! times that drift. Set `TRANSFORMERS_GEMMA_TOLERANCE` to override it for
//! other checkpoints or backends. Greedy tokens are compared
//! while the reference's top-2 margin exceeds twice the tolerance; at least
//! [`DEFAULT_MIN_GREEDY`] = 2 tokens must be compared
//! (`TRANSFORMERS_GEMMA_MIN_GREEDY` overrides the minimum).
//!
//! # Long context
//!
//! The short prompts never reach Gemma 3 4B's 1024-token sliding window, so
//! there every sliding layer behaves like a global one and no ring wraps. A
//! second bundle holds one 1237-token prompt: sixty numbered field notes and
//! a question about the first, generated by
//!
//! ```text
//! colors = ["red", "blue", "green", "amber", "violet", "silver", "orange"]
//! animals = ["fox", "heron", "otter", "lynx", "badger", "falcon", "beaver",
//!            "marten", "wren", "hare", "ibex"]
//! places = ["the river", "the old mill", "the north ridge", "the orchard",
//!           "the harbor", "the quarry", "the meadow", "the chapel", "the bridge"]
//! lines = [f"Entry {i}: the {colors[i % 7]} {animals[i % 11]} walked to "
//!          f"{places[i % 9]} and counted {(i * 37) % 101} stones."
//!          for i in range(1, 61)]
//! prompt = ("Field notes.\n" + "\n".join(lines)
//!           + "\nQuestion: In entry 1, where did the animal walk? Answer:")
//! ```
//!
//! and passed as the only `--prompt` of the reference script with
//! `--greedy-tokens 8` (the pinned bundle's logits SHA-256 is
//! `16d961fe03e8e7fbb75c6be0e005ba903d0cad8e3b847c22b2232826346a9330`; the
//! reference answers " the old mill", which only the global layers can read
//! 1200 tokens back). The tests check stateless logits on both sides of the
//! window; that disabling the window moves the logits at and beyond it far
//! outside the tolerance while leaving earlier positions unchanged, so the
//! comparison is decisive; and a cached run whose capacity exceeds the
//! window, so sliding layers live in 1024-slot rings, whose second prefill
//! chunk wraps those rings, followed by the cached greedy continuation.
//!
//! F32 drift grows with context: on this prompt Transformers' own eager and
//! SDPA graphs (both F32, same weights) disagree by up to `3.2e-3`, so the
//! long-context tolerance [`DEFAULT_LONG_TOLERANCE`] is `5e-3`
//! (`TRANSFORMERS_GEMMA_LONG_TOLERANCE` overrides it). Measured on
//! Flex/F32: stateless logits deviate by at most `5.5e-4` before the window
//! and `1.2e-3` at or beyond it, with no step at the boundary (`1.6e-4` over
//! its first eight positions); without the window they deviate by `1.7`
//! within eight positions of it and by up to `36` later, while earlier
//! positions are unchanged. The cached run stores 29 of 34 layers in rings,
//! its chunk ends deviate by `1.5e-4` and `6.9e-5`, and all 8 greedy tokens
//! match.

