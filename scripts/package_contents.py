"""Which repository evidence the published crate carries.

crates.io limits an upload to 10 MiB compressed, and the repository's complete
measurement history is several times that. The ``include`` list in
``Cargo.toml`` therefore splits the evidence:

* Published: the checkpoint support records ``acceptance/*.json``; the one
  summary record per measurement campaign, ``acceptance/measurements/*.json``,
  with that directory's ``README.md``; and the compact summaries in
  ``acceptance/measurements/small-model-performance-20260910/``, which the v0.1
  release record names (by path and SHA-256) as its approved timing baseline.
* Repository-only: every other campaign directory
  ``acceptance/measurements/<campaign>/`` (raw logs, coverage exports, replay
  reports, copied lockfiles and runner scripts), and the recorded outputs of
  the mechanistic example studies below ``examples/mechanistic/``: rendered
  figures, ``result.json`` records, and captured ``evidence/`` and
  ``results/`` runs. Their programs, protocols, fixtures and tests are
  published.

``scripts/check_release.py`` rejects a package listing that contains
repository-only evidence. The record tests in ``scripts/tests`` read such
evidence through ``scripts/tests/repository_evidence.py``, which skips them in
the extracted archive (identified by :func:`is_packaged_archive`) and lets
them fail in a Git checkout when a file is missing.
"""

from __future__ import annotations

from pathlib import Path, PurePath


# Campaign directories below acceptance/measurements/ that the crate publishes
# whole. Keep this in step with the include list in Cargo.toml.
PUBLISHED_CAMPAIGNS = frozenset({"small-model-performance-20260910"})

# Rendered figures of the mechanistic studies: regenerated by each study's
# plot script, and the bulk of the examples' bytes.
EXAMPLE_FIGURE_SUFFIXES = frozenset({".png", ".svg"})

# Captured run directories inside one mechanistic study.
EXAMPLE_RUN_DIRECTORIES = frozenset({"evidence", "results"})


def is_published_evidence(path: PurePath) -> bool:
    """Whether a repository-relative ``acceptance/`` path is in the published crate.

    Raises ``ValueError`` for a path outside ``acceptance/``, which this
    policy does not classify.
    """

    parts = path.parts
    if not parts or parts[0] != "acceptance" or len(parts) < 2:
        raise ValueError(f"not an acceptance evidence path: {path}")
    if len(parts) == 2:
        return path.suffix == ".json"
    if parts[1] != "measurements":
        return False
    if len(parts) == 3:
        return path.suffix == ".json" or path.name == "README.md"
    return parts[2] in PUBLISHED_CAMPAIGNS


def is_example_output(path: PurePath) -> bool:
    """Whether a repository-relative path is a recorded mechanistic-study output.

    Outputs are the figures, the ``result.json`` and ``*.result.json``
    records, and everything below a study's ``evidence/`` or ``results/``
    directory. Paths outside ``examples/mechanistic/`` are never outputs.
    """

    parts = path.parts
    if parts[:2] != ("examples", "mechanistic") or len(parts) < 3:
        return False
    return (path.suffix in EXAMPLE_FIGURE_SUFFIXES
            or path.name == "result.json"
            or path.name.endswith(".result.json")
            or (len(parts) > 4 and parts[3] in EXAMPLE_RUN_DIRECTORIES))


def is_packaged_archive(root: Path) -> bool:
    """Whether ``root`` is a crate extracted from a ``cargo package`` archive.

    Cargo writes the author's original manifest beside the normalized one as
    ``Cargo.toml.orig`` in every archive; a Git checkout never contains it.
    """

    return (root / "Cargo.toml.orig").is_file()
