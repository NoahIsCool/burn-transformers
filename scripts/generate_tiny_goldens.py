def file_sha256(path: Path) -> str:
    """Hash a file's exact bytes."""

    return hashlib.sha256(path.read_bytes()).hexdigest()


def float_list(tensor: Any) -> Any:
    """Convert an F32 tensor to nested lists of shortest round-trip decimal strings' values."""

    return [float(format(value, ".9g")) for value in tensor.reshape(-1).tolist()]


def golden_inputs(torch: Any) -> tuple[Any, Any, Any]:
    """Build seeded token IDs, a validity mask, and explicit positions.

    Row 0 is unpadded. Row 1 is left-padded with ``PADDING`` pad tokens; its
    valid tokens start at position 0, matching ``generate``'s cumulative-mask
    positions rather than ``forward``'s implicit ``arange`` positions.
    """

    generator = torch.Generator().manual_seed(1234)
    ids = torch.randint(3, VOCAB_SIZE, (2, SEQUENCE_LENGTH), generator=generator)
    mask = torch.ones_like(ids)
    ids[1, :PADDING] = 0
    mask[1, :PADDING] = 0
    positions = (mask.cumsum(-1) - 1).clamp(min=0)
    return ids, mask, positions


def initialize(model: Any, model_type: str, torch: Any) -> None:
    """Draw informative seeded weights.

    Matrices use N(0, 0.08^2) and biases N(0, 0.02^2). Normalization weights
    are centered at the module's identity: zero for Gemma's ``1 + w``
    parameterization and one elsewhere. gpt-oss sink logits use N(0, 0.5^2).
    """

    torch.manual_seed(0)
    zero_centered = model_type.startswith("gemma")
    with torch.no_grad():
        for name, parameter in model.named_parameters():
            if "sinks" in name:
                parameter.normal_(0.0, 0.5)
            elif "norm" in name and parameter.ndim == 1:
                parameter.normal_(0.0, 0.1)
                if not zero_centered:
                    parameter.add_(1.0)
            elif parameter.ndim == 1:
                parameter.normal_(0.0, 0.02)
            else:
                parameter.normal_(0.0, 0.08)


def generate_case(name: str, output: Path, script_sha256: str) -> dict[str, Any]:
    """Build one case, write its checkpoint and golden, and return a summary."""

    import torch
    import transformers

    model_type, overrides, purpose = CASES[name]
    torch.use_deterministic_algorithms(True)
    torch.set_num_threads(1)
    settings = dict(COMMON)
    settings.update(overrides)
    config = transformers.CONFIG_MAPPING[model_type](**settings)
    config._attn_implementation = "eager"
    model = transformers.AutoModelForCausalLM.from_config(config, torch_dtype=torch.float32)
    model.eval()
    initialize(model, model_type, torch)

    ids, mask, positions = golden_inputs(torch)
    with torch.no_grad():
        output_full = model(
            input_ids=ids,
            attention_mask=mask,
            position_ids=positions,
            output_hidden_states=True,
            use_cache=False,
        )
        prompt = ids[:1, :GREEDY_PROMPT]
        greedy = model.generate(
            input_ids=prompt,
            attention_mask=torch.ones_like(prompt),
            max_new_tokens=GREEDY_NEW_TOKENS,
            do_sample=False,
            use_cache=True,
            pad_token_id=0,
            eos_token_id=None,
        )

    directory = output / name
    directory.mkdir(parents=True, exist_ok=True)
    model.save_pretrained(directory, safe_serialization=True)
    for extra in ("generation_config.json",):
        (directory / extra).unlink(missing_ok=True)

    golden = {
        "schema_version": 1,
        "case": name,
        "model_type": model_type,
        "purpose": purpose,
        "generator": {
            "script": "scripts/generate_tiny_goldens.py",
            "script_sha256": script_sha256,
            "transformers": transformers.__version__,
            "torch": torch.__version__,
            "attention_implementation": "eager",
            "dtype": "float32",
        },
        "checkpoint_sha256": file_sha256(directory / "model.safetensors"),
        "input_ids": ids.tolist(),
        "attention_mask": mask.tolist(),
        "position_ids": positions.tolist(),
        "logits_shape": list(output_full.logits.shape),
        "logits": float_list(output_full.logits),
        "hidden_states_row0_shape": [len(output_full.hidden_states), SEQUENCE_LENGTH, settings["hidden_size"]],
        "hidden_states_row0": float_list(torch.stack([state[0] for state in output_full.hidden_states])),
        "greedy_prompt": prompt[0].tolist(),
        "greedy_tokens": greedy[0, GREEDY_PROMPT:].tolist(),
    }
    (directory / "golden.json").write_text(json.dumps(golden, indent=1, sort_keys=True) + "\n")
    return {"case": name, "parameters": sum(p.numel() for p in model.parameters())}


def main() -> int:
    """Parse arguments and generate the requested cases."""

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--case", action="append", choices=sorted(CASES))
    args = parser.parse_args()
    script_sha256 = file_sha256(Path(__file__).resolve())
    for name in args.case or sorted(CASES):
        print(json.dumps(generate_case(name, args.output, script_sha256)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
