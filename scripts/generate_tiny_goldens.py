#!/usr/bin/env python3
"""Generate tiny random-weight checkpoints and golden outputs for architecture parity.

Each case instantiates one Hugging Face Transformers architecture with a tiny
configuration chosen to exercise that family's distinctive mechanisms (RoPE
scaling variants, attention bias, Q/K normalization, sliding windows, NoPE
layers, soft-capping, sandwich norms, attention sinks, mixture-of-experts
routing, post-normalization). Weights are drawn from a seeded distribution that
is wider than the library default so logits are informative, then saved with
``save_pretrained`` as F32 SafeTensors next to ``golden.json``.

The golden records the exact inputs and explicit position IDs, full-vocabulary
F32 logits for every position of an unpadded row and a left-padded row,
per-layer hidden states for the unpadded row, and a cached greedy continuation.
Rust integration tests load the checkpoint with the crate's strict loader and
compare against these values, so architecture parity runs in ordinary
``cargo test`` without large downloads.

Python is used because the reference is the official PyTorch implementation.
The script never contacts a model hub: architectures are built from local
configuration objects of the installed ``transformers`` package.

Usage::

    python3 scripts/generate_tiny_goldens.py --output tests/fixtures/tiny_goldens [--case NAME ...]
"""

